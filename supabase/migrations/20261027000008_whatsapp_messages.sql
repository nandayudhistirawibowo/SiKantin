BEGIN;

CREATE TABLE IF NOT EXISTS public.messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wa_message_id text NOT NULL UNIQUE,
    sender_jid text NOT NULL,
    push_name text,
    message_type text NOT NULL,
    message_text text,
    message_timestamp timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS messages_message_timestamp_idx
    ON public.messages (message_timestamp DESC);

ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.messages FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.messages TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.messages_id_seq TO service_role;

COMMIT;
